// ToPascalCase converts RouterOS kebab-case or dot-prefixed names to idiomatic Go PascalCase.
// Examples:
//   ".id"             -> "ID"
//   "caller-id"       -> "CallerID"
//   "local-address"   -> "LocalAddress"
//   "dns-server"      -> "DNSServer"
//   "change-tcp-mss"  -> "ChangeTCPMSS"
//   "use-upnp"        -> "UseUPnP"
//   "limit-bytes-in"  -> "LimitBytesIn"
func ToPascalCase(s string) string {
	s = strings.TrimPrefix(s, ".")
	if s == "" {
		return "Field"
	}

	parts := strings.FieldsFunc(s, func(r rune) bool {
		return r == '-' || r == '_' || r == ' ' || r == '.' || r == '/' || r == ','
	})

	var result []string
	for _, p := range parts {
		if p == "" {
			continue
		}
		lower := strings.ToLower(p)
		if init, ok := knownInitialisms[lower]; ok {
			result = append(result, init)
			continue
		}
		// Capitalize first rune
		runes := []rune(p)
		runes[0] = []rune(strings.ToUpper(string(runes[0])))[0]
		result = append(result, string(runes))
	}

	return strings.Join(result, "")
}

// MapRosTypeToGo maps a RouterOS syntax type string to a Go primitive or type.
func MapRosTypeToGo(rosName, rosType string, isOptionalForSet bool) string {
	lowerName := strings.ToLower(rosName)
	lowerType := strings.ToLower(rosType)

	switch {
	case lowerType == "bool" || lowerType == "yes|no":
		if isOptionalForSet {
			return "*bool"
		}
		return "bool"
	case lowerType == "int64" || lowerType == "num" || lowerType == "integer":
		if strings.Contains(lowerName, "bytes") || strings.Contains(lowerName, "quota") ||
			strings.Contains(lowerName, "count") || strings.Contains(lowerName, "packets") || lowerType == "int64" {
			if isOptionalForSet {
				return "*int64"
			}
			return "int64"
		}
		if isOptionalForSet {
			return "*int"
		}
		return "int"
	case lowerType == "int":
		if isOptionalForSet {
			return "*int"
		}
		return "int"
	case lowerType == "array" || strings.HasSuffix(lowerType, "-list"):
		return "[]string"
	default:
		// Strings, IPs, time durations, hexadecimal IDs
		return "string"
	}
}

// GeneratorOptions configures code generation output.
type GeneratorOptions struct {
	PackageName string // e.g. "ppp"
	RootMenu    string // e.g. "ppp"
}

// GenerateSource generates a complete Go source file for the given submenus.
func GenerateSource(schemas []*SubmenuSchema, opts GeneratorOptions) ([]byte, error) {
	pkgName := opts.PackageName
	if pkgName == "" {
		pkgName = strings.ToLower(opts.RootMenu)
		if pkgName == "" {
			pkgName = "mikrotik"
		}
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by rosgen (/console/inspect); DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Root menu: /%s\n\n", strings.ReplaceAll(opts.RootMenu, ",", "/"))
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)

	domainPrefix := ToPascalCase(opts.RootMenu)

	// Sort submenus for deterministic output
	sort.Slice(schemas, func(i, j int) bool {
		return schemas[i].Name < schemas[j].Name
	})

	for _, sub := range schemas {
		subNamePascal := ToPascalCase(sub.Name)
		subPrefix := domainPrefix + subNamePascal
		if strings.HasSuffix(domainPrefix, subNamePascal) {
			subPrefix = domainPrefix
		}

		fmt.Fprintf(&buf, "// ─────────────────────────────────────────────────────────────────────────────\n")
		fmt.Fprintf(&buf, "// Submenu: /%s\n", strings.ReplaceAll(sub.FullPath, ",", "/"))
		if sub.Description != "" {
			fmt.Fprintf(&buf, "// %s\n", sub.Description)
		}
		fmt.Fprintf(&buf, "// ─────────────────────────────────────────────────────────────────────────────\n\n")

		// 1. Entity struct (from 'print' command or first available command)
		if printCmd, hasPrint := sub.Commands["print"]; hasPrint {
			entityStruct := buildEntityStruct(subPrefix, sub, printCmd)
			renderStruct(&buf, entityStruct)
		}

		// 2. Add Request struct (from 'add' command)
		if addCmd, hasAdd := sub.Commands["add"]; hasAdd {
			addStruct := buildAddStruct(subPrefix+"AddRequest", sub, addCmd)
			renderStruct(&buf, addStruct)
		}

		// 3. Set Request struct (from 'set' command)
		if setCmd, hasSet := sub.Commands["set"]; hasSet {
			setStruct := buildSetStruct(subPrefix+"SetRequest", sub, setCmd)
			renderStruct(&buf, setStruct)
		}
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), fmt.Errorf("gofmt error: %w\nraw code:\n%s", err, buf.String())
	}

	return formatted, nil
}

func buildEntityStruct(name string, sub *SubmenuSchema, cmd Command) GeneratedStruct {
	st := GeneratedStruct{
		Name:    name,
		Doc:     fmt.Sprintf("%s represents a row returned by /%s/print.", name, strings.ReplaceAll(sub.FullPath, ",", "/")),
		Command: "print",
	}

	seen := make(map[string]bool)
	for _, arg := range cmd.Arguments {
		if seen[arg.Name] {
			continue
		}
		seen[arg.Name] = true

		fieldName := ToPascalCase(arg.Name)
		goType := MapRosTypeToGo(arg.Name, arg.Type, false)
		tag := fmt.Sprintf(`json:"%s,omitempty" ros:"%s"`, arg.Name, arg.Name)

		doc := arg.Description
		if doc == "" {
			doc = fmt.Sprintf("RouterOS property %s", arg.Name)
		}

		st.Fields = append(st.Fields, GeneratedField{
			Name:     fieldName,
			Type:     goType,
			RosName:  arg.Name,
			Tag:      tag,
			Doc:      doc,
			Required: arg.Required,
		})
	}

	return st
}

func buildAddStruct(name string, sub *SubmenuSchema, cmd Command) GeneratedStruct {
	st := GeneratedStruct{
		Name:    name,
		Doc:     fmt.Sprintf("%s holds parameter options for /%s/add.", name, strings.ReplaceAll(sub.FullPath, ",", "/")),
		Command: "add",
	}

	seen := make(map[string]bool)
	for _, arg := range cmd.Arguments {
		if arg.Name == ".id" || seen[arg.Name] {
			continue
		}
		seen[arg.Name] = true

		fieldName := ToPascalCase(arg.Name)
		goType := MapRosTypeToGo(arg.Name, arg.Type, false)

		tag := fmt.Sprintf(`json:"%s,omitempty" ros:"%s"`, arg.Name, arg.Name)
		if arg.Required {
			tag = fmt.Sprintf(`json:"%s" ros:"%s" validate:"required"`, arg.Name, arg.Name)
		}

		doc := arg.Description
		if arg.Default != "" {
			doc += fmt.Sprintf(" (default: %q)", arg.Default)
		}

		st.Fields = append(st.Fields, GeneratedField{
			Name:     fieldName,
			Type:     goType,
			RosName:  arg.Name,
			Tag:      tag,
			Doc:      doc,
			Required: arg.Required,
		})
	}

	return st
}

func hasIDInPrint(sub *SubmenuSchema) bool {
	if printCmd, ok := sub.Commands["print"]; ok {
		for _, arg := range printCmd.Arguments {
			if arg.Name == ".id" {
				return true
			}
		}
	}
	return false
}

func buildSetStruct(name string, sub *SubmenuSchema, cmd Command) GeneratedStruct {
	st := GeneratedStruct{
		Name:    name,
		Doc:     fmt.Sprintf("%s holds parameter options for /%s/set.", name, strings.ReplaceAll(sub.FullPath, ",", "/")),
		Command: "set",
	}

	// For list-based resources, ensure an ID field exists to target the item to update.
	// Singleton resources (such as /ppp/aaa) do not use IDs.
	if cmd.HasNumbers || hasIDInPrint(sub) {
		st.Fields = append(st.Fields, GeneratedField{
			Name:     "ID",
			Type:     "string",
			RosName:  ".id",
			Tag:      `json:".id" ros:".id" validate:"required"`,
			Doc:      "Internal ID (*HEX) or selector of the item to update",
			Required: true,
		})
	}

	seen := map[string]bool{".id": true, "numbers": true}
	for _, arg := range cmd.Arguments {
		if seen[arg.Name] {
			continue
		}
		seen[arg.Name] = true

		fieldName := ToPascalCase(arg.Name)
		goType := MapRosTypeToGo(arg.Name, arg.Type, true)
		tag := fmt.Sprintf(`json:"%s,omitempty" ros:"%s"`, arg.Name, arg.Name)

		st.Fields = append(st.Fields, GeneratedField{
			Name:     fieldName,
			Type:     goType,
			RosName:  arg.Name,
			Tag:      tag,
			Doc:      arg.Description,
			Required: false,
		})
	}

	return st
}

func renderStruct(buf *bytes.Buffer, st GeneratedStruct) {
	fmt.Fprintf(buf, "// %s\n", st.Doc)
	fmt.Fprintf(buf, "type %s struct {\n", st.Name)
	for _, f := range st.Fields {
		if f.Doc != "" {
			fmt.Fprintf(buf, "\t// %s\n", f.Doc)
		}
		fmt.Fprintf(buf, "\t%s %s `%s`\n", f.Name, f.Type, f.Tag)
	}
	fmt.Fprintf(buf, "}\n\n")
}
